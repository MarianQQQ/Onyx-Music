import { createSignal, createMemo } from "solid-js";
import { triggerPluginToast } from "./pluginManager";

// 0% CPU/GPU Load AI Song Filter
// Fast regex targeting AI music generators, vocal models, and cover clones
export const AI_KEYWORDS_REGEX =
  /\b(suno(?:\.ai)?|udio(?:\.ai)?|diff-svc|rvc|so-vits|weights\.gg|aimova|ai[-_\s]?mova|midjourney|chatgpt|voice clone|generated by|ai generated|ai vocals|ai remake)\b|(?:[\(\[](?:ai|ші)[^\)\]]*[\)\]])|(?:^|[^\p{L}\p{N}])(?:ai|ші)\s*(?:cover|версія|кавер|remake|remix|version)(?:$|[^\p{L}\p{N}])|штучний\s*інтелект/iu;

export const STANDALONE_AI_ARTIST_REGEX =
  /(?:^|[^\p{L}\p{N}])(?:ai|ші)(?:$|[^\p{L}\p{N}])|\b(ai|ші)\b/iu;

export const DEFAULT_BLOCKED_ARTISTS: string[] = [
  "ai mova",
  "draugr balled",
  "suno",
  "udio",
];

const STORAGE_KEY_ENABLED = "ytm_filter_ai_enabled";
const STORAGE_KEY_BLOCKED = "ytm_ai_blocked_artists";

const initialEnabled = (): boolean => {
  try {
    const saved = localStorage.getItem(STORAGE_KEY_ENABLED);
    return saved !== null ? saved === "true" : true;
  } catch {
    return true;
  }
};

const initialBlockedArtists = (): string[] => {
  try {
    const saved = localStorage.getItem(STORAGE_KEY_BLOCKED);
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed)) {
        const list = parsed.map((item) => String(item).trim()).filter(Boolean);
        const lowerSet = new Set(list.map((a) => a.toLowerCase()));
        for (const farm of DEFAULT_BLOCKED_ARTISTS) {
          if (!lowerSet.has(farm.toLowerCase())) {
            list.push(farm);
          }
        }
        return list;
      }
    }
  } catch {}
  return [...DEFAULT_BLOCKED_ARTISTS];
};

// Reactive Solid Signals
export const [aiFilterEnabled, setAiFilterEnabledSignal] = createSignal<boolean>(initialEnabled());
export const [blockedArtists, setBlockedArtistsSignal] = createSignal<string[]>(initialBlockedArtists());

// Fast O(1) case-insensitive lookup set
const blockedArtistsSet = createMemo(() => {
  return new Set(blockedArtists().map((a) => a.trim().toLowerCase()));
});

/**
 * Checks whether AI filter is currently enabled.
 */
export function isAiFilterEnabled(): boolean {
  return aiFilterEnabled();
}

/**
 * Toggles AI filter status (or sets explicit boolean).
 */
export function toggleAiFilter(enabled?: boolean): boolean {
  const next = enabled !== undefined ? enabled : !aiFilterEnabled();
  setAiFilterEnabledSignal(next);
  try {
    localStorage.setItem(STORAGE_KEY_ENABLED, String(next));
  } catch (e) {
    console.warn("Failed to persist AI filter enabled state:", e);
  }
  return next;
}

/**
 * Adds an artist or channel to the AI blocked list.
 */
export function blockArtist(artistName: string): boolean {
  if (!artistName || !artistName.trim()) return false;
  const trimmed = artistName.trim();
  const current = blockedArtists();
  const exists = current.some((a) => a.toLowerCase() === trimmed.toLowerCase());
  if (exists) return false;

  const nextList = [...current, trimmed];
  setBlockedArtistsSignal(nextList);
  try {
    localStorage.setItem(STORAGE_KEY_BLOCKED, JSON.stringify(nextList));
  } catch (e) {
    console.warn("Failed to persist blocked artists:", e);
  }
  return true;
}

/**
 * Removes an artist from the AI blocked list.
 */
export function unblockArtist(artistName: string): boolean {
  if (!artistName) return false;
  const target = artistName.trim().toLowerCase();
  const current = blockedArtists();
  const nextList = current.filter((a) => a.trim().toLowerCase() !== target);
  if (nextList.length !== current.length) {
    setBlockedArtistsSignal(nextList);
    try {
      localStorage.setItem(STORAGE_KEY_BLOCKED, JSON.stringify(nextList));
    } catch (e) {
      console.warn("Failed to persist blocked artists:", e);
    }
    return true;
  }
  return false;
}

/**
 * Resets the entire AI blacklist.
 */
export function clearBlockedArtists(): void {
  setBlockedArtistsSignal([]);
  try {
    localStorage.setItem(STORAGE_KEY_BLOCKED, JSON.stringify([]));
  } catch (e) {
    console.warn("Failed to clear blocked artists:", e);
  }
}

/**
 * Returns the current list of blocked artist names.
 */
export function getBlockedArtists(): string[] {
  return blockedArtists();
}

/**
 * High-performance 0% CPU check for AI tracks using regex and O(1) set lookup.
 */
export function isAiTrack(track: {
  title?: string;
  artist?: string;
  uploader?: string;
  year?: string;
  subtitle?: string;
  [key: string]: any;
}): boolean {
  if (!track) return false;

  const title = (track.title || "").trim();
  const artist = (track.artist || "").trim();
  const uploader = (track.uploader || "").trim();
  const year = (track.year || "").trim();
  const subtitle = (track.subtitle || "").trim();

  // 1. Instant regex check on title, artist, uploader, year & subtitle
  if (title && AI_KEYWORDS_REGEX.test(title)) return true;
  if (artist && AI_KEYWORDS_REGEX.test(artist)) return true;
  if (uploader && AI_KEYWORDS_REGEX.test(uploader)) return true;
  if (year && AI_KEYWORDS_REGEX.test(year)) return true;
  if (subtitle && AI_KEYWORDS_REGEX.test(subtitle)) return true;

  // 2. Standalone AI in artist or uploader name (e.g. "AI MOVA", "AI Project", "AI Hits", "AI Singer")
  if (artist && STANDALONE_AI_ARTIST_REGEX.test(artist)) return true;
  if (uploader && STANDALONE_AI_ARTIST_REGEX.test(uploader)) return true;

  // 3. Blocked artists blacklist match
  const blockedList = blockedArtists();
  if (blockedList.length > 0) {
    const set = blockedArtistsSet();
    const artistLower = artist.toLowerCase();
    const uploaderLower = uploader.toLowerCase();
    const yearLower = year.toLowerCase();
    const subtitleLower = subtitle.toLowerCase();

    if (artistLower && set.has(artistLower)) return true;
    if (uploaderLower && set.has(uploaderLower)) return true;
    if (yearLower && set.has(yearLower)) return true;
    if (subtitleLower && set.has(subtitleLower)) return true;

    // Substring match for compound artist names or subtitles
    for (const b of blockedList) {
      const bLower = b.toLowerCase();
      if (!bLower) continue;
      if (artistLower && artistLower.includes(bLower)) return true;
      if (uploaderLower && uploaderLower.includes(bLower)) return true;
      if (yearLower && yearLower.includes(bLower)) return true;
      if (subtitleLower && subtitleLower.includes(bLower)) return true;
    }
  }

  return false;
}

/**
 * Filters an array of tracks, omitting AI tracks if filter is enabled.
 */
export function filterTracks<T extends { title?: string; artist?: string }>(tracks: T[]): T[] {
  if (!isAiFilterEnabled()) {
    return tracks;
  }
  if (!Array.isArray(tracks)) {
    return [];
  }
  return tracks.filter((track) => !isAiTrack(track));
}

/**
 * Shows desktop / in-app notification toast.
 */
export function showNotification(title: string, body: string, icon?: string) {
  triggerPluginToast({
    title,
    body,
    icon,
  });

  if ("Notification" in window && Notification.permission === "granted") {
    try {
      new Notification(title, { body, icon });
    } catch {}
  }
}

export const aiFilter = {
  isEnabled: isAiFilterEnabled,
  isAiFilterEnabled,
  toggle: toggleAiFilter,
  toggleAiFilter,
  blockArtist,
  unblockArtist,
  clearBlockedArtists,
  getBlockedArtists,
  isAiTrack,
  filterTracks,
  showNotification,
};

export default aiFilter;
